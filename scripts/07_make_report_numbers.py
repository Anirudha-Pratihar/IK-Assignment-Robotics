#!/usr/bin/env python3
"""STEP 7 - write report/numbers.tex (LaTeX macros) from results/*/summary.csv so the prose in report/main.tex always matches the data.
   python scripts/07_make_report_numbers.py   (run after 04_analyze_results.py for every tag)"""
import os, pandas as pd
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
M = {"Mink": "Mink", "DLS": "DLS", "QP": "QP"}
out = ["% AUTO-GENERATED by scripts/07_make_report_numbers.py - do not edit"]

def S(tag, sub=""):
    p = os.path.join(ROOT, "results", sub, tag, "summary.csv")
    return pd.read_csv(p).set_index("method") if os.path.exists(p) else None

def mac(name, val): out.append(f"\\newcommand{{\\{name}}}{{{val}}}")

for tag, pre in [("main", "main"), ("stress", "stress"), ("stress_retry4", "retry"), ("lowcarry_noCA", "lcNoCA"), ("lowcarry_ca", "lcCA"), ("lowcarry_smart", "lcSmart"), ("fast", "fast")]:
    df = S(tag)
    for m in M:
        for key, col, fmt in [("Succ", None, None), ("Ms", "plan_ms", "{:.0f}"), ("Iter", "ik_iters", "{:.0f}"), ("Vel", "vel_ev", "{:.0f}"), ("Lim", "lim_ev", "{:.0f}"),
                              ("Track", "track_mm", "{:.1f}"), ("Place", "place_mm", "{:.1f}"), ("MaxDq", "max_dq", "{:.2f}"), ("ClrC", "clr_cube_mm", "{:.0f}"), ("ClrR", "clr_robot_mm", "{:.0f}")]:
            if df is None or m not in df.index: v = "n/a"
            elif key == "Succ": v = f"{int(df.loc[m,'success'])}/{int(df.loc[m,'n'])}"
            else:
                x = df.loc[m, col]; v = "n/a" if pd.isna(x) else fmt.format(x)
            mac(f"{pre}{key}{m}", v)
# ---- Franka (combined set; tag "main" under results/franka) ----
import json
df = S("main", "franka")
for m in M:
    for key, col, fmt in [("Ms", "plan_ms", "{:.0f}"), ("Iter", "ik_iters", "{:.0f}"), ("Track", "track_mm", "{:.1f}"), ("Place", "place_mm", "{:.1f}"), ("ClrC", "clr_cube_mm", "{:.0f}"), ("ClrR", "clr_robot_mm", "{:.0f}"), ("Vel", "vel_ev", "{:.0f}")]:
        mac(f"fr{key}{m}", "n/a" if df is None or m not in df.index else fmt.format(df.loc[m, col]))
    mac(f"frSucc{m}", "n/a" if df is None or m not in df.index else f"{int(df.loc[m,'success'])}/{int(df.loc[m,'n'])}")
    mac(f"frN{m}", "n/a" if df is None or m not in df.index else f"{int(df.loc[m,'n'])}")
    mac(f"frRem{m}", "n/a" if df is None or m not in df.index else f"{25-int(df.loc[m,'n'])}")
dj = os.path.join(ROOT, "configs", "franka", "table_design.json")
if os.path.exists(dj):
    d = json.load(open(dj)); mac("frH", f"{d['H']:.2f}"); mac("frL", f"{d['L']:.2f}"); mac("frW", f"{d['W']:.2f}")
open(os.path.join(ROOT, "report", "numbers.tex"), "w").write("\n".join(out) + "\n"); print("wrote report/numbers.tex")
